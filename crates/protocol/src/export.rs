use std::{error::Error, fs, path::Path};

use ts_rs::{Config, TS};

use crate::{AgentMessage, HostInfo, HubMessage, MetricsFrame, MinuteRollup, api::*};

#[test]
fn export_typescript() -> Result<(), Box<dyn Error>> {
    // Resolve export_to paths from the workspace, regardless of Cargo's test working directory.
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let config = Config::new().with_out_dir(&root);
    let output = root.join("web/src/api/generated");
    let mut index =
        String::from("// Generated by cargo test -p moni-protocol --features ts. Do not edit.\n");

    macro_rules! export {
        ($($ty:ty),+ $(,)?) => {
            $(
                <$ty>::export(&config)?;
                let name = stringify!($ty);
                let binding = fs::read_to_string(output.join(format!("{name}.ts")))?;
                assert!(!binding.contains("bigint"), "{name} must use number for 64-bit integers");
                index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
            )+
        };
    }

    export!(
        ActiveAlert,
        AgentMessage,
        AlertEvent,
        AlertKind,
        AlertMetric,
        AlertOp,
        AlertRule,
        AlertRuleInput,
        AlertRulePatch,
        AlertTestResponse,
        ApiError,
        ApiErrorCode,
        AppConfig,
        AuthMeResponse,
        CreateServerRequest,
        CreateServerResponse,
        DashboardEvent,
        History,
        HistoryPoint,
        HistoryRange,
        HostInfo,
        HubMessage,
        LoginRequest,
        MetricsFrame,
        MinuteRollup,
        Notifications,
        Retention,
        ServerStatus,
        TokenResponse,
        Traffic,
        UpdateServerRequest,
    );
    fs::write(output.join("index.ts"), index)?;

    let status = ServerStatus::decl(&config);
    assert!(status.contains("last_seen_ms: number | null"));
    assert!(status.contains("host: HostInfo | null"));
    assert!(status.contains("metrics: MetricsFrame | null"));
    let patch = AlertRulePatch::decl(&config);
    assert!(patch.contains("server_id?: string | null"));
    assert!(patch.contains("recover_threshold?: number | null"));
    assert!(patch.contains("enabled?: boolean"));
    assert!(CreateServerRequest::decl(&config).contains("id?: string"));
    assert!(UpdateServerRequest::decl(&config).contains("name?: string"));
    Ok(())
}
